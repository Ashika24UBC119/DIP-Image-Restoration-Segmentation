# IMAGE PROCESSING FUNCTIONS

def read_grayscale(image_path):

    image = cv2.imread(str(image_path))

    if image is None:
        raise ValueError(
            f"Could not read image: {image_path}"
        )

    gray = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )

    return gray

# GAUSSIAN NOISE

def add_gaussian_noise(image, sigma=25):

    noise = np.random.normal(
        0,
        sigma,
        image.shape
    )

    noisy = image.astype(np.float32) + noise

    noisy = np.clip(
        noisy,
        0,
        255
    )

    return noisy.astype(np.uint8)

# SALT AND PEPPER NOISE

def add_salt_pepper_noise(
    image,
    amount=0.05
):

    noisy = image.copy()

    total_pixels = image.size

    number_of_pixels = int(
        amount * total_pixels
    )

    random_indices = np.random.choice(
        total_pixels,
        number_of_pixels,
        replace=False
    )

    flat = noisy.reshape(-1)

    half = number_of_pixels // 2

    # Salt
    flat[random_indices[:half]] = 255

    # Pepper
    flat[random_indices[half:]] = 0

    return noisy

# MEAN FILTER

def mean_filter(image, kernel_size=5):

    return cv2.blur(
        image,
        (kernel_size, kernel_size)
    )

# MEDIAN FILTER

def median_filter(image, kernel_size=5):

    return cv2.medianBlur(
        image,
        kernel_size
    )

# ADAPTIVE MEDIAN FILTER

def adaptive_median_filter(image):

    median_3 = cv2.medianBlur(
        image,
        3
    )

    median_5 = cv2.medianBlur(
        image,
        5
    )

    median_7 = cv2.medianBlur(
        image,
        7
    )

    result = median_3.copy()

    # Detect extreme pixels
    mask = (
        (image <= 5)
        |
        (image >= 250)
    )

    result[mask] = median_5[mask]

    # Remaining extreme pixels
    mask2 = (
        (result <= 5)
        |
        (result >= 250)
    )

    result[mask2] = median_7[mask2]

    return result

# IMAGE QUALITY METRICS

def calculate_metrics(
    original,
    restored
):

    mse = mean_squared_error(
        original,
        restored
    )

    psnr = peak_signal_noise_ratio(
        original,
        restored,
        data_range=255
    )

    ssim = structural_similarity(
        original,
        restored,
        data_range=255
    )

    return mse, psnr, ssim


