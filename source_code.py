# LOAD BSDS500 GROUND-TRUTH BOUNDARIES

def load_ground_truth_boundary(
    mat_path
):

    data = loadmat(
        str(mat_path),
        squeeze_me=True,
        struct_as_record=False
    )

    ground_truth = data["groundTruth"]

    ground_truth = np.asarray(
        ground_truth
    ).ravel()

    boundary_maps = []

    for item in ground_truth:

        try:

            boundary = np.asarray(
                item.Boundaries,
                dtype=np.float32
            )

            if boundary.ndim == 2:

                boundary_maps.append(
                    boundary
                )

        except Exception:
            continue

    if len(boundary_maps) == 0:

        raise ValueError(
            "No boundary annotations found."
        )

    # Consensus of human annotations
    stack = np.stack(
        boundary_maps,
        axis=0
    )

    consensus = (
        np.mean(stack, axis=0) >= 0.5
    )

    return consensus.astype(
        np.uint8
    )


