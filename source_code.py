# OTSU THRESHOLDING

def otsu_segmentation(image):

    _, binary = cv2.threshold(
        image,
        0,
        255,
        cv2.THRESH_BINARY + cv2.THRESH_OTSU
    )

    return binary

# MORPHOLOGICAL CLEANUP

def morphological_cleanup(
    binary
):

    kernel = np.ones(
        (3, 3),
        np.uint8
    )

    opened = cv2.morphologyEx(
        binary,
        cv2.MORPH_OPEN,
        kernel
    )

    cleaned = cv2.morphologyEx(
        opened,
        cv2.MORPH_CLOSE,
        kernel
    )

    return cleaned

# CANNY EDGE DETECTION

def canny_segmentation(
    image
):

    return cv2.Canny(
        image,
        50,
        150
    )


# IoU

def calculate_iou(
    prediction,
    ground_truth
):

    prediction = prediction > 0
    ground_truth = ground_truth > 0

    intersection = np.logical_and(
        prediction,
        ground_truth
    ).sum()

    union = np.logical_or(
        prediction,
        ground_truth
    ).sum()

    if union == 0:
        return 1.0

    return intersection / union

# DICE

def calculate_dice(
    prediction,
    ground_truth
):

    prediction = prediction > 0
    ground_truth = ground_truth > 0

    intersection = np.logical_and(
        prediction,
        ground_truth
    ).sum()

    denominator = (
        prediction.sum()
        + ground_truth.sum()
    )

    if denominator == 0:
        return 1.0

    return (
        2 * intersection
        / denominator
    )


